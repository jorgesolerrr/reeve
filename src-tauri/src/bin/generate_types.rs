//! Generates `app/src/generated/types.ts` from the Rust source of truth.
//!
//! The registry below is **explicit**: a type reaches the frontend only when a
//! human adds it here, so the frontend contract is reviewable as a diff and
//! nothing leaks across the boundary by accident (05-lld-skeleton).
//!
//! - `cargo run --bin generate_types` — write the file.
//! - `cargo run --bin generate_types -- --check` — fail if the committed file
//!   has drifted from the Rust types. This is CI's enforcement layer 4.

use std::fs;
use std::path::PathBuf;
use std::process::ExitCode;

use reeve_core::dto::{ApiError, ApiErrorCode, ErrorDetails};
use ts_rs::TS;

/// **The registry.** Add a type here, or the frontend never sees it.
///
/// Order is the file's order: keep related types adjacent, since the output is
/// read by humans reviewing a diff.
fn registry() -> String {
    let mut out = String::from(HEADER);
    declare::<ApiError>(&mut out);
    declare::<ApiErrorCode>(&mut out);
    declare::<ErrorDetails>(&mut out);
    out
}

const HEADER: &str = "\
// Generated by `cargo run --bin generate_types`. Do not edit by hand.
// The registry that produced it: src-tauri/src/bin/generate_types.rs

";

/// One declaration, exported. Every registered type lands in this single file,
/// so declarations reference each other by bare name and need no imports.
fn declare<T: TS>(out: &mut String) {
    out.push_str("export ");
    out.push_str(&T::decl());
    out.push_str("\n\n");
}

fn output_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("src-tauri always has a workspace root above it")
        .join("app/src/generated/types.ts")
}

/// Line endings are not drift: a Windows checkout may hold CRLF, and the check
/// must mean "the types changed", never "the clone did".
fn normalize(text: &str) -> String {
    text.replace("\r\n", "\n")
}

fn main() -> ExitCode {
    let generated = registry();
    let path = output_path();
    let check = std::env::args().any(|arg| arg == "--check");

    if check {
        let committed = match fs::read_to_string(&path) {
            Ok(text) => text,
            Err(err) => {
                eprintln!(
                    "generate_types --check: cannot read {}: {err}",
                    path.display()
                );
                eprintln!("run `cargo run --bin generate_types` and commit the result");
                return ExitCode::FAILURE;
            }
        };
        if normalize(&committed) == normalize(&generated) {
            println!("generate_types --check: {} is up to date", path.display());
            return ExitCode::SUCCESS;
        }
        eprintln!(
            "generate_types --check: {} has drifted from the Rust types",
            path.display()
        );
        eprintln!("run `cargo run --bin generate_types` and commit the result");
        return ExitCode::FAILURE;
    }

    if let Some(parent) = path.parent() {
        if let Err(err) = fs::create_dir_all(parent) {
            eprintln!("generate_types: cannot create {}: {err}", parent.display());
            return ExitCode::FAILURE;
        }
    }
    if let Err(err) = fs::write(&path, &generated) {
        eprintln!("generate_types: cannot write {}: {err}", path.display());
        return ExitCode::FAILURE;
    }
    println!("generate_types: wrote {}", path.display());
    ExitCode::SUCCESS
}
